def _attachment_rows(meta):
    """证据附件页码索引：页数连续时自动累加页码；一旦缺页数，其后一律留「（待填）」。

    设计：页码必须能被复核——所以宁可留空，也不跨过缺口继续累加（那会得出错误页码）。
    """
    items = meta.get("证据附件清单") or TEMPLATE["证据附件清单"]
    st = _num(meta.get("附件起始页码"))
    start = int(st) if (st and st > 0) else 1
    cols = ["附件编号", "附件名称", "对应底稿索引", "页数", "页码（起-止）", "存放方式", "数据来源"]
    rows, page, broken = [], start, False
    for r in items:
        n = _num(r.get("页数"))
        if (n is None) or (n <= 0):
            broken = True
            rows.append([_v(r, c) for c in cols[:4]] + ["（待填：须在装订后手工填写）"]
                         + [_v(r, cols[5]), _v(r, cols[6])])
            continue
        n = int(n)
        rng = ("第 %d 页" % page) if n == 1 else ("第 %d-%d 页" % (page, page + n - 1))
        if not broken:
            page += n
        rows.append([_v(r, cols[0]), _v(r, cols[1]), _v(r, cols[2]), n, rng,
                     _v(r, cols[5]), _v(r, cols[6])])
    total = (page - start) if not broken else "（待填：有附件未填页数，须装订后合计）"
    return cols, rows, start, total, broken


