    lvl = (r3.get("gate") or {}).get("level", "?")
    _record(os.path.basename(r3["md"]), D_PBC, "资料索取清单说明", lvl)
    if lvl not in ("PASS", "WARN"):
        failed.append(os.path.basename(r3["md"]))
    emit("资料交接签收单.md", D_PBC, "资料交接、原件核验与签收记录", *doc_handover(meta))

    # 04 审计底稿与证据
