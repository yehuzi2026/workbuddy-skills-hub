PORTFOLIO_COLS = ["序号", "项目名称", "项目编号", "审计类型", "委托单位", "审计期间",
                  "送审价(万元)", "审定价(万元)", "审减额(万元)", "审减率",
                  "问题数", "未销号数", "争议数", "当前阶段", "档案目录", "数据来源"]


def _num(v):
    """能转成数字就转，否则返回 None（缺失一律不代填）。"""
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def _stage(m):
    """当前阶段：按已填信息推断最小可信结论，不猜。"""
    if m.get("当前阶段"):
        return m.get("当前阶段")
    if _num(m.get("审定价")) is not None:
        return "已出审定结论"
    if m.get("问题清单"):
        return "已发现问题、待整改"
    if m.get("检查范围明细"):
        return "已定检查范围、待实施"
    return "（待填）"


def collect_projects(root_dir):
    """扫描目录下所有「项目信息.json」，收集为多项目台账数据。"""
    rows = []
    for dirpath, dirnames, filenames in os.walk(root_dir):
        dirnames[:] = sorted(d for d in dirnames if d not in ("__pycache__", ".git"))
        if "项目信息.json" not in filenames:
            continue
        fp = os.path.join(dirpath, "项目信息.json")
        try:
            m = _read_json(fp)
        except Exception as exc:
            m = {"项目名称": "（项目信息.json 读取失败：%s）" % exc}
        rows.append({"meta": m, "dir": dirpath})
    rows.sort(key=lambda r: str(r["meta"].get("项目编号") or r["meta"].get("项目名称") or ""))
    return rows


def build_portfolio(root_dir, out_dir):
    """生成多项目总台账（xlsx + md）。缺项一律「（待填）」，合计只累计有值的行。"""
    rows, agg = [], {"送审": 0.0, "审定": 0.0, "审减": 0.0, "问题": 0, "未销号": 0, "争议": 0}
    for i, r in enumerate(collect_projects(root_dir), 1):
        m, src = r["meta"], (r["meta"].get("数据来源") or "（待填：项目信息.json 未填数据来源）")
        sub, fin = _num(m.get("送审价")), _num(m.get("审定价"))
        red = (sub - fin) if (sub is not None and fin is not None) else None
        issues = m.get("问题清单") or []
        open_cnt = sum(1 for x in issues if str(x.get("状态", "")).strip() not in ("已销号", "已整改"))
        dis = m.get("争议清单") or []
        rate = ("%.2f%%" % (red / sub * 100)) if (red is not None and sub) else "（待填）"
        rows.append([i, m.get("项目名称") or "（待填）", m.get("项目编号") or "（待填）",
                     m.get("审计类型") or "（待填）", m.get("委托单位") or "（待填）",
                     m.get("审计期间") or "（待填）",
                     ("%.2f" % sub) if sub is not None else "（待填）",
                     ("%.2f" % fin) if fin is not None else "（待填）",
                     (("%.2f" % red) if red is not None else "（待填）"), rate,
                     len(issues) if issues else 0, open_cnt, len(dis) if dis else 0,
                     _stage(m), r["dir"], src])
        if sub is not None:
            agg["送审"] += sub
        if fin is not None:
            agg["审定"] += fin
        if red is not None:
            agg["审减"] += red
        agg["问题"] += len(issues)
        agg["未销号"] += open_cnt
        agg["争议"] += len(dis)
    os.makedirs(out_dir, exist_ok=True)
    xlsx = dv.build_table("审计项目总台账", PORTFOLIO_COLS, rows, os.path.join(out_dir, "审计项目总台账.xlsx"))
    secs = [
        ("一、总览",
         "扫描范围：%s；识别依据：各项目档案目录下的 项目信息.json"
         "（数据来源：本工具的多项目台账规则）。" % root_dir + LF +
         "纳入项目数：%d 个（数据来源：各项目档案目录下的 项目信息.json 文件清单）。" % len(rows) + LF +
         "送审合计 %.2f 万元、审定合计 %.2f 万元、审减合计 %.2f 万元"
         "（数据来源：各项目 项目信息.json 逐项加总，缺项不计入合计）。"
         % (agg["送审"], agg["审定"], agg["审减"]) + LF +
         "问题合计 %d 项，其中未销号 %d 项（数据来源：各项目 问题清单）。"
         % (agg["问题"], agg["未销号"]) + LF +
         "争议合计 %d 项（数据来源：各项目 争议清单）。" % agg["争议"]),
        ("二、项目清单", _table(PORTFOLIO_COLS, rows, 200)),
        ("三、使用说明",
         "1）本台账为审计组的进度与问题总览，不替代各项目档案内的正式文件"
         "（数据来源：本工具的多项目台账规则）。" + LF +
         "2）「（待填）」表示该项目信息未提供该项，本台账不代为编造；补全后重跑即可刷新"
         "（数据来源：本工具的多项目台账规则）。" + LF +
         "3）审减额 = 送审价 − 审定价，仅在两者都有值时计算并纳入合计"
         "（数据来源：本工具的多项目台账规则）。" + LF +
         "4）未销号数 = 问题台账中状态不属于「已销号 / 已整改」的条数"
         "（数据来源：本工具的多项目台账规则）。"),
        ("四、依据", dv._provenance(STD_DEFAULT, "各项目档案目录下的 项目信息.json")),
    ]
    md = dv.build_report("审计项目总台账", secs, os.path.join(out_dir, "审计项目总台账.md"))
    return {"xlsx": xlsx, "md": md, "count": len(rows), "agg": agg,
            "gate": (dv.gate_check(md) or {}).get("level", "?")}


def _read_json(path):
    """读入项目信息 JSON：兼容 UTF-8 / UTF-8 BOM / UTF-16（Windows 下 > 重定向会写成 UTF-16）。"""
    with io.open(path, "rb") as f:
        raw = f.read()
    if raw.startswith(b"\xef\xbb\xbf"):
        txt = raw.decode("utf-8-sig")
    elif raw.startswith(b"\xff\xfe") or raw.startswith(b"\xfe\xff"):
        txt = raw.decode("utf-16")
    else:
        txt = raw.decode("utf-8")
    return json.loads(txt)


def main(argv=None):
    ap = argparse.ArgumentParser(description="审计项目成套模板生成器（工程造价审计 · 项目档案装箱）")
    ap.add_argument("--meta", help="项目信息 JSON 文件路径（可用 --print-template 生成模板）")
    ap.add_argument("--portfolio", metavar="目录", help="多项目总台账：扫描该目录下所有「项目信息.json」，汇总为总台账（xlsx + md）")
    ap.add_argument("--out", default="./_项目档案", help="输出目录（默认 ./_项目档案）")
    ap.add_argument("--demo", action="store_true", help="用内置示例数据生成整套档案")
    ap.add_argument("--print-template", action="store_true", help="打印可填写的项目信息 JSON 模板")
    ap.add_argument("--save-template", metavar="路径", help="把可填写的项目信息模板保存为 UTF-8 的 JSON 文件（Windows 的 > 重定向会写成 UTF-16，请用本参数）")
    a = ap.parse_args(argv)

    if a.portfolio:
        if not os.path.isdir(a.portfolio):
            print(json.dumps({"错误": "找不到目录：%s" % a.portfolio}, ensure_ascii=False))
            return 2
        out = a.out if a.out != "./_项目档案" else "./_审计项目总台账"
        try:
            res = build_portfolio(a.portfolio, out)
        except Exception as exc:
            print(json.dumps({"错误": "总台账生成失败：%s" % exc}, ensure_ascii=False))
            return 2
        print("审计项目总台账已生成：%s" % res["md"])
        print("项目数 %d；送审合计 %.2f 万元、审定合计 %.2f 万元、审减合计 %.2f 万元"
              % (res["count"], res["agg"]["送审"], res["agg"]["审定"], res["agg"]["审减"]))
        print("表格：%s" % res["xlsx"])
        print("门禁自检：%s" % res["gate"])
        if res["gate"] not in ("PASS", "WARN"):
            return 1
        return 0
    if a.save_template:
        with io.open(a.save_template, "w", encoding="utf-8", newline="") as f:
            f.write(json.dumps(TEMPLATE, ensure_ascii=False, indent=2) + LF)
        print("已保存可填写的项目信息模板（UTF-8）：%s" % a.save_template)
        if not (a.demo or a.meta or a.print_template):
            return 0
    if a.print_template:
        print(json.dumps(TEMPLATE, ensure_ascii=False, indent=2))
        return 0
    if a.demo:
        meta = DEMO_META
    elif a.meta:
        if not os.path.isfile(a.meta):
            print(json.dumps({"错误": "找不到项目信息文件：%s" % a.meta}, ensure_ascii=False))
            return 2
        try:
            meta = _read_json(a.meta)
        except Exception as exc:
            print(json.dumps({"错误": "项目信息文件读不出来或不是合法 JSON（%s）：%s" % (exc, a.meta)},
                             ensure_ascii=False))
            return 2
    else:
        print("请指定项目信息：--meta 项目信息.json；" + LF +
              "  先导出模板：--save-template 项目信息.json（推荐，UTF-8）；或加 --demo 看示例。")
        return 2

    try:
        res = build_project(meta, a.out)
    except Exception as exc:
        print(json.dumps({"错误": "生成失败：%s" % exc}, ensure_ascii=False))
        return 2

    print("审计项目档案已生成：%s" % res["root"])
    print("文件 %d 份（含表格与输入文件）：" % len(res["records"]))
    for r in res["records"]:
        print("  [%s] %s/%s  —— %s" % (str(r["gate"]), r["dir"], r["name"], r["purpose"]))
    if res["failed"]:
        print("⚠ 以下文件未通过门禁，须补数据来源或计算式后重新生成：%s" % "、".join(res["failed"]))
        return 1
    print("门禁自检：全部放行（PASS/WARN）✅")
    return 0


if __name__ == "__main__":
    sys.exit(main())