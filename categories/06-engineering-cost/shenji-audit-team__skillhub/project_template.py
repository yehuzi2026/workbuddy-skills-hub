def _table(headers, rows, maxlen=70):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(dv._flat(c, maxlen) for c in r) + " |")
    return LF.join(out)


