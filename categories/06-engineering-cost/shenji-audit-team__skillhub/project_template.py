def build_project(meta, out_root):
    """按固定目录结构生成整套审计项目档案。返回 {"root","records","failed"}。"""
    meta = dict(meta or {})
    root = os.path.abspath(out_root)
    for d in DIRS:
        os.makedirs(os.path.join(root, d), exist_ok=True)
    records, failed = [], []

    def _record(name, folder, purpose, gate):
        records.append({"name": name, "dir": folder or "（根目录）", "purpose": purpose, "gate": gate})

    def emit(name, folder, purpose, title, sections):
        path = os.path.join(root, folder, name) if folder else os.path.join(root, name)
        dv.build_report(title, sections, path)
        lvl = (dv.gate_check(path) or {}).get("level", "?")
        _record(name, folder, purpose, lvl)
        if lvl not in ("PASS", "WARN"):
            failed.append(name)
        return lvl

    def emit_table(name, folder, purpose, title, columns, rows):
        path = os.path.join(root, folder, name)
        dv.build_table(title, columns, rows, path)
        _record(name, folder, purpose, "—（表格）")

    # 01 审前调查与立项
    emit("审前调查表.md", D_SURVEY, "开工前的项目与被审计单位情况调查", *doc_survey(meta))
    emit("独立性声明与保密承诺.md", D_SURVEY, "审计人员独立性与保密签署件", *doc_independence(meta))
    emit("外聘人员与回避记录.md", D_SURVEY, "外聘人员登记、回避声明与独立性排查留痕", *doc_outstaff(meta))
    emit("审计组分工与联系方式.md", D_SURVEY, "审计组构成、分工与三级复核要求", *doc_team(meta))

    # 02 审计实施方案
    plan, plan_error = None, ""
    plan_items = [r for r in (meta.get("检查范围明细") or []) if _numeric(r.get("送审金额(万元)"))]
    try:
        if plan_items:
            plan = ce.sample_plan(
                [{"项目": r.get("送审事项") or ("第%d项" % (i + 1)), "金额": float(r["送审金额(万元)"])}
                 for i, r in enumerate(plan_items)],
                threshold_rate=float(meta.get("必查阈值率", 0.05) or 0.05),
                coverage_target=float(meta.get("覆盖目标", 0.70) or 0.70),
                name="%s · 检查范围方案" % _v(meta, "项目名称"))
    except Exception as exc:
        plan_error = "检查范围方案生成失败：%s" % exc
    emit("审计实施方案.md", D_PLAN, "本项目审计的目标、范围、方法、进度、分工与检查范围", *doc_audit_plan(meta, plan, plan_error))
    if plan:
        rows = []
        for way, bucket in zip(("必查", "抽中", "未覆盖"), _plan_buckets(plan)):
            for x in bucket:
                rows.append([x.get("项目", ""), x.get("金额", ""), way])
        emit_table("检查范围与抽样方案.xlsx", D_PLAN, "必查 / 抽中 / 未覆盖三类检查范围（引擎实算）",
                   "检查范围与抽样方案", ["送审事项", "送审金额(万元)", "检查方式"], rows)

    # 03 资料索取与交接
    pbc_items = meta.get("资料清单") or TEMPLATE["资料清单"]
    pbc_meta = {"项目名": _v(meta, "项目名称"), "要求提供时间": _v(meta, "资料提供时间"),
                "数据来源": _src(meta)}
    r3 = dv.pbc_list(pbc_items, pbc_meta, os.path.join(root, D_PBC))
